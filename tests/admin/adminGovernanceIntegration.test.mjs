test('Organization picker invalidates selection by role/search, blocks stale responses, and paginates', () => {
  const view = read('src/views/admin/organizations/AdminOrganizationsView.vue')
  const roleHandler = view.slice(view.indexOf('const changeAssignmentRole'), view.indexOf('const selectCandidate'))
  assert.match(roleHandler, /selectedCandidate\.value = null/)
  assert.match(roleHandler, /candidates\.value = \[\]/)
  assert.match(roleHandler, /candidatePage\.value = 1/)
  assert.match(roleHandler, /loadCandidates\(\)/)
  assert.match(view, /watch\(candidateSearch[\s\S]{0,220}candidatePage\.value = 1[\s\S]{0,100}loadCandidates\(\)/)
  assert.match(view, /setTimeout\([\s\S]{0,180}, 300\)/)
  assert.match(view, /request !== candidateRequestId[\s\S]{0,220}candidateSearch\.value !== search/)
  assert.match(view, /assignmentRole, search: search \|\| undefined, page, limit:/)
  assert.match(view, /changeCandidatePage/)
  assert.match(view, /candidatePagination\.totalPages > 1/)
  assert.match(view, /正在載入符合條件的使用者/)
  assert.match(view, /找不到符合目前指派條件的使用者/)
  assert.match(view, /status === 403|response\?\.status === 403/)
  assert.match(view, /status === 409|response\?\.status === 409/)
  assert.match(view, /status === 422|response\?\.status === 422/)
})

