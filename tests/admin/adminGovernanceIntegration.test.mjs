import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const root = new URL('../../', import.meta.url)
const read = (path) => readFileSync(new URL(path, root), 'utf8')

test('current User models canonical multi-capabilities without JWT or storage authority', () => {
  const auth = read('src/api/auth.ts')
  const helpers = read('src/config/capabilities.ts')
  const store = read('src/stores/authStore.ts')
  assert.match(auth, /capabilities\?: Capability\[\]/)
  for (const capability of ['MEMBER', 'SALES', 'SALES_SUPERVISOR', 'PLATFORM_MANAGER', 'ADMIN']) assert.match(helpers, new RegExp(capability))
  assert.match(helpers, /normalized\.has\('SALES_SUPERVISOR'\)[\s\S]{0,80}normalized\.add\('SALES'\)/)
  assert.match(helpers, /Array\.isArray\(user\.capabilities\)[\s\S]{0,100}LEGACY_ROLE_CAPABILITIES/)
  assert.match(store, /hasCapability\(user\.value, 'ADMIN'\)/)
  assert.doesNotMatch(`${helpers}\n${store}`, /localStorage|sessionStorage|decode|jwt/i)
})

